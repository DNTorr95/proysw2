-- =====================================================================
-- V5: vínculos entre oficios (HU-06 / CU-06, defecto D-01).
-- Un oficio de respuesta o de reiteración se vincula con el oficio original.
-- Agrega 1 tabla (el modelo pasa de 44 a 45 tablas). No modifica las existentes.
-- =====================================================================
CREATE TABLE vinculo_correspondencia (
    id_vinculo          INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_correspondencia  INTEGER     NOT NULL,                  -- oficio original
    id_vinculado        INTEGER     NOT NULL,                  -- respuesta o reiteración
    tipo                VARCHAR(20) NOT NULL,                  -- RESPUESTA, REITERACION
    id_usuario          INTEGER     NOT NULL,                  -- quién registró el vínculo
    fecha               TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_vinculo_correspondencia PRIMARY KEY (id_vinculo),
    CONSTRAINT fk_vinculo_original  FOREIGN KEY (id_correspondencia) REFERENCES correspondencia (id_correspondencia),
    CONSTRAINT fk_vinculo_vinculado FOREIGN KEY (id_vinculado)       REFERENCES correspondencia (id_correspondencia),
    CONSTRAINT fk_vinculo_usuario   FOREIGN KEY (id_usuario)         REFERENCES usuario (id_usuario),
    CONSTRAINT ck_vinculo_tipo      CHECK (tipo IN ('RESPUESTA', 'REITERACION')),
    CONSTRAINT ck_vinculo_distinto  CHECK (id_correspondencia <> id_vinculado),
    CONSTRAINT uq_vinculo_par       UNIQUE (id_correspondencia, id_vinculado)
);

CREATE INDEX ix_vinculo_vinculado ON vinculo_correspondencia (id_vinculado);
