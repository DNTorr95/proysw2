-- =====================================================================
-- Proyecto 25 - Script base de 34 tablas (PostgreSQL 16)
-- Sistema Web de Gestión Administrativa con RPA
-- Dirección de Carrera de Psicología - UAGRM
--
-- Orden de ejecución:
--   1) Este script (34 tablas)                       -> Flyway V1
--   2) Proyecto25_Script_SQL_Complementario.sql      -> Flyway V2 (10 tablas)
--   3) Proyecto25_Script_SQL_Ajustes.sql             -> Flyway V2_1 (6 FK de conexión)
--   4) Proyecto25_Seed_Basico_PostgreSQL.sql         -> Flyway V3 (datos ficticios)
--
-- Las tablas que crea el complementario (permiso, rol_permiso, estado_tramite,
-- transicion_estado, incidencia_rpa, alerta, extraccion_ocr, trabajo_grado,
-- registro_migracion, evento) NO se crean aquí.
-- Los roles NO se insertan aquí: los inserta el complementario.
-- =====================================================================

-- =====================================================================
-- MÓDULO 1. SEGURIDAD Y PERSONAS (8 tablas)
-- =====================================================================

CREATE TABLE rol (
    id_rol      INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombre      VARCHAR(50)  NOT NULL,
    descripcion VARCHAR(200),
    CONSTRAINT pk_rol PRIMARY KEY (id_rol),
    CONSTRAINT uq_rol_nombre UNIQUE (nombre)
);

CREATE TABLE persona (
    id_persona INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    ci         VARCHAR(20)  NOT NULL,
    nombres    VARCHAR(100) NOT NULL,
    apellidos  VARCHAR(100) NOT NULL,
    correo     VARCHAR(150),
    telefono   VARCHAR(20),
    CONSTRAINT pk_persona PRIMARY KEY (id_persona),
    CONSTRAINT uq_persona_ci UNIQUE (ci)
);

-- Un usuario tiene un único rol (id_rol).
CREATE TABLE usuario (
    id_usuario        INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_persona        INTEGER      NOT NULL,
    id_rol            INTEGER      NOT NULL,
    nombre_usuario    VARCHAR(50)  NOT NULL,
    contrasena_hash   VARCHAR(100) NOT NULL,
    estado            VARCHAR(20)  NOT NULL DEFAULT 'ACTIVO',   -- ACTIVO, BLOQUEADO, INACTIVO
    intentos_fallidos INTEGER      NOT NULL DEFAULT 0,
    ultimo_acceso     TIMESTAMP,
    fecha_creacion    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_usuario PRIMARY KEY (id_usuario),
    CONSTRAINT uq_usuario_nombre UNIQUE (nombre_usuario),
    CONSTRAINT uq_usuario_persona UNIQUE (id_persona),
    CONSTRAINT ck_usuario_estado CHECK (estado IN ('ACTIVO', 'BLOQUEADO', 'INACTIVO')),
    CONSTRAINT fk_usuario_persona FOREIGN KEY (id_persona) REFERENCES persona (id_persona),
    CONSTRAINT fk_usuario_rol     FOREIGN KEY (id_rol)     REFERENCES rol (id_rol)
);

-- Especialización de Persona: Director, Coordinador y Apoyo Profesional.
CREATE TABLE personal_administrativo (
    id_persona             INTEGER      NOT NULL,
    cargo                  VARCHAR(100) NOT NULL,
    area                   VARCHAR(100),
    fecha_designacion      DATE,
    resolucion_designacion VARCHAR(100),
    CONSTRAINT pk_personal_administrativo PRIMARY KEY (id_persona),
    CONSTRAINT fk_personal_persona FOREIGN KEY (id_persona) REFERENCES persona (id_persona)
);

CREATE TABLE estudiante (
    id_persona INTEGER     NOT NULL,
    registro   VARCHAR(20) NOT NULL,
    plan       VARCHAR(20) NOT NULL,                       -- 148-1, 148-2
    estado     VARCHAR(20) NOT NULL DEFAULT 'REGULAR',     -- REGULAR, CONDICIONAL, LICENCIA, EGRESADO, TITULADO, ABANDONO
    CONSTRAINT pk_estudiante PRIMARY KEY (id_persona),
    CONSTRAINT uq_estudiante_registro UNIQUE (registro),
    CONSTRAINT fk_estudiante_persona FOREIGN KEY (id_persona) REFERENCES persona (id_persona)
);

CREATE TABLE docente (
    id_persona     INTEGER     NOT NULL,
    codigo_docente VARCHAR(20) NOT NULL,
    categoria      VARCHAR(30),                            -- A, B, C, INTERINO
    dedicacion     VARCHAR(30),                            -- TIEMPO_COMPLETO, MEDIO_TIEMPO, HORARIO
    especialidad   VARCHAR(100),
    CONSTRAINT pk_docente PRIMARY KEY (id_persona),
    CONSTRAINT uq_docente_codigo UNIQUE (codigo_docente),
    CONSTRAINT fk_docente_persona FOREIGN KEY (id_persona) REFERENCES persona (id_persona)
);

-- Bitácora de solo inserción (CU-03).
CREATE TABLE bitacora_auditoria (
    id_evento    BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_usuario   INTEGER,                                  -- NULL para procesos del sistema
    accion       VARCHAR(80)  NOT NULL,
    entidad      VARCHAR(80)  NOT NULL,
    id_entidad   VARCHAR(50),
    fecha_hora   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    direccion_ip VARCHAR(45),
    detalle      TEXT,
    CONSTRAINT pk_bitacora_auditoria PRIMARY KEY (id_evento),
    CONSTRAINT fk_bitacora_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario)
);
CREATE INDEX ix_bitacora_fecha   ON bitacora_auditoria (fecha_hora);
CREATE INDEX ix_bitacora_entidad ON bitacora_auditoria (entidad, id_entidad);

-- Transferencia de autoridad de Dirección (CU-04).
CREATE TABLE transferencia_autoridad (
    id_transferencia   INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_usuario_origen  INTEGER      NOT NULL,
    id_usuario_destino INTEGER      NOT NULL,
    motivo             VARCHAR(300) NOT NULL,
    resolucion         VARCHAR(100),
    fecha_inicio       DATE         NOT NULL,
    fecha_fin          DATE,
    estado             VARCHAR(20)  NOT NULL DEFAULT 'VIGENTE',   -- VIGENTE, FINALIZADA, REVOCADA
    CONSTRAINT pk_transferencia_autoridad PRIMARY KEY (id_transferencia),
    CONSTRAINT ck_transferencia_usuarios CHECK (id_usuario_origen <> id_usuario_destino),
    CONSTRAINT fk_transferencia_origen  FOREIGN KEY (id_usuario_origen)  REFERENCES usuario (id_usuario),
    CONSTRAINT fk_transferencia_destino FOREIGN KEY (id_usuario_destino) REFERENCES usuario (id_usuario)
);

-- =====================================================================
-- MÓDULO 2. TRÁMITES ESTUDIANTILES (5 tablas)
-- =====================================================================

CREATE TABLE tipo_tramite (
    id_tipo_tramite       INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombre                VARCHAR(100) NOT NULL,
    descripcion           VARCHAR(300),
    plazo_referencia_dias INTEGER      NOT NULL,
    requiere_dictamen     BOOLEAN      NOT NULL DEFAULT FALSE,
    activo                BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_tipo_tramite PRIMARY KEY (id_tipo_tramite),
    CONSTRAINT uq_tipo_tramite_nombre UNIQUE (nombre),
    CONSTRAINT ck_tipo_tramite_plazo CHECK (plazo_referencia_dias > 0)
);

CREATE TABLE requisito_tipo_tramite (
    id_requisito    INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_tipo_tramite INTEGER      NOT NULL,
    descripcion     VARCHAR(200) NOT NULL,
    obligatorio     BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_requisito_tipo_tramite PRIMARY KEY (id_requisito),
    CONSTRAINT fk_requisito_tipo FOREIGN KEY (id_tipo_tramite) REFERENCES tipo_tramite (id_tipo_tramite)
);

-- Expediente administrativo (CU-08): agrupa trámites y documentos de un estudiante o asunto.
CREATE TABLE expediente (
    id_expediente  INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    codigo         VARCHAR(30)  NOT NULL,
    id_estudiante  INTEGER,
    titulo         VARCHAR(200) NOT NULL,
    descripcion    TEXT,
    estado         VARCHAR(20)  NOT NULL DEFAULT 'ABIERTO',   -- ABIERTO, CERRADO
    fecha_apertura DATE         NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT pk_expediente PRIMARY KEY (id_expediente),
    CONSTRAINT uq_expediente_codigo UNIQUE (codigo),
    CONSTRAINT fk_expediente_estudiante FOREIGN KEY (id_estudiante) REFERENCES estudiante (id_persona)
);

-- estado_actual se enlaza a estado_tramite(nombre) en el script de ajustes.
-- Solo cambia mediante Spring State Machine.
CREATE TABLE tramite (
    id_tramite          INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    numero              VARCHAR(30) NOT NULL,
    id_tipo_tramite     INTEGER     NOT NULL,
    id_estudiante       INTEGER     NOT NULL,
    id_expediente       INTEGER,
    id_usuario_registro INTEGER     NOT NULL,
    fecha_recepcion     TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_limite        DATE        NOT NULL,
    fecha_cierre        TIMESTAMP,
    estado_actual       VARCHAR(30) NOT NULL DEFAULT 'RECEPCIONADO',
    prioridad           VARCHAR(10) NOT NULL DEFAULT 'MEDIA',    -- ALTA, MEDIA, BAJA
    observaciones       TEXT,
    CONSTRAINT pk_tramite PRIMARY KEY (id_tramite),
    CONSTRAINT uq_tramite_numero UNIQUE (numero),
    CONSTRAINT ck_tramite_prioridad CHECK (prioridad IN ('ALTA', 'MEDIA', 'BAJA')),
    CONSTRAINT fk_tramite_tipo       FOREIGN KEY (id_tipo_tramite)     REFERENCES tipo_tramite (id_tipo_tramite),
    CONSTRAINT fk_tramite_estudiante FOREIGN KEY (id_estudiante)       REFERENCES estudiante (id_persona),
    CONSTRAINT fk_tramite_expediente FOREIGN KEY (id_expediente)       REFERENCES expediente (id_expediente),
    CONSTRAINT fk_tramite_usuario    FOREIGN KEY (id_usuario_registro) REFERENCES usuario (id_usuario)
);
CREATE INDEX ix_tramite_estado ON tramite (estado_actual);

CREATE TABLE historial_estado (
    id_historial   INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_tramite     INTEGER     NOT NULL,
    id_transicion  INTEGER,                         -- FK a transicion_estado (script de ajustes)
    estado_origen  VARCHAR(30),                     -- NULL en el registro inicial
    estado_destino VARCHAR(30) NOT NULL,
    evento         VARCHAR(50) NOT NULL,
    id_usuario     INTEGER     NOT NULL,
    fecha_hora     TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    observacion    TEXT,
    CONSTRAINT pk_historial_estado PRIMARY KEY (id_historial),
    CONSTRAINT fk_historial_tramite FOREIGN KEY (id_tramite) REFERENCES tramite (id_tramite),
    CONSTRAINT fk_historial_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario)
);
CREATE INDEX ix_historial_tramite ON historial_estado (id_tramite, fecha_hora);

-- =====================================================================
-- MÓDULO 3. CORRESPONDENCIA Y DOCUMENTOS (7 tablas)
-- =====================================================================

-- Dependencias/unidades a las que se dirige o de las que proviene la correspondencia.
CREATE TABLE destinatario (
    id_destinatario INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombre          VARCHAR(150) NOT NULL,
    cargo           VARCHAR(100),
    unidad          VARCHAR(150) NOT NULL,
    institucion     VARCHAR(150) NOT NULL DEFAULT 'UAGRM',
    correo          VARCHAR(150),
    activo          BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_destinatario PRIMARY KEY (id_destinatario)
);

CREATE TABLE correspondencia (
    id_correspondencia  INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    codigo              VARCHAR(30)  NOT NULL,
    tipo                VARCHAR(20)  NOT NULL,                  -- RECIBIDA, EMITIDA
    asunto              VARCHAR(300) NOT NULL,
    descripcion         TEXT,
    fecha_documento     DATE         NOT NULL,
    fecha_registro      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id_destinatario     INTEGER      NOT NULL,                  -- dependencia de origen (RECIBIDA) o destino (EMITIDA)
    estado              VARCHAR(20)  NOT NULL DEFAULT 'REGISTRADA', -- REGISTRADA, DERIVADA, EN_TRAMITE, RESPONDIDA, ARCHIVADA
    autorizado          BOOLEAN      NOT NULL DEFAULT FALSE,    -- solo los autorizados entran al RPA
    id_usuario_registro INTEGER      NOT NULL,
    CONSTRAINT pk_correspondencia PRIMARY KEY (id_correspondencia),
    CONSTRAINT uq_correspondencia_codigo UNIQUE (codigo),
    CONSTRAINT ck_correspondencia_tipo CHECK (tipo IN ('RECIBIDA', 'EMITIDA')),
    CONSTRAINT fk_correspondencia_destinatario FOREIGN KEY (id_destinatario)     REFERENCES destinatario (id_destinatario),
    CONSTRAINT fk_correspondencia_usuario      FOREIGN KEY (id_usuario_registro) REFERENCES usuario (id_usuario)
);
CREATE INDEX ix_correspondencia_fecha ON correspondencia (fecha_documento, tipo);

CREATE TABLE seguimiento_correspondencia (
    id_seguimiento     INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_correspondencia INTEGER     NOT NULL,
    fecha              TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    estado             VARCHAR(20) NOT NULL,
    observacion        TEXT,
    CONSTRAINT pk_seguimiento_correspondencia PRIMARY KEY (id_seguimiento),
    CONSTRAINT fk_seguimiento_correspondencia FOREIGN KEY (id_correspondencia) REFERENCES correspondencia (id_correspondencia)
);

CREATE TABLE plantilla_documento (
    id_plantilla   INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombre         VARCHAR(150) NOT NULL,
    tipo           VARCHAR(50)  NOT NULL,          -- INFORME_RPA, OFICIO, CORREO
    version        VARCHAR(20)  NOT NULL,
    contenido_html TEXT         NOT NULL,
    vigente        BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_plantilla_documento PRIMARY KEY (id_plantilla),
    CONSTRAINT uq_plantilla_nombre_version UNIQUE (nombre, version)
);

-- Archivos del volumen documental (/var/storage/documentos/).
-- Un archivo puede pertenecer a una correspondencia o a un expediente;
-- los archivos de trámites se enlazan mediante documento_tramite.
CREATE TABLE archivo_adjunto (
    id_archivo         INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombre_archivo     VARCHAR(255) NOT NULL,
    tipo_mime          VARCHAR(100) NOT NULL,
    tamano_bytes       BIGINT       NOT NULL,
    hash_sha256        CHAR(64)     NOT NULL,
    ruta               VARCHAR(500) NOT NULL,
    fecha_carga        TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id_usuario_carga   INTEGER      NOT NULL,
    id_correspondencia INTEGER,
    id_expediente      INTEGER,
    descripcion        VARCHAR(300),
    CONSTRAINT pk_archivo_adjunto PRIMARY KEY (id_archivo),
    CONSTRAINT uq_archivo_ruta UNIQUE (ruta),
    CONSTRAINT ck_archivo_tamano CHECK (tamano_bytes > 0 AND tamano_bytes <= 10485760),
    CONSTRAINT fk_archivo_usuario         FOREIGN KEY (id_usuario_carga)   REFERENCES usuario (id_usuario),
    CONSTRAINT fk_archivo_correspondencia FOREIGN KEY (id_correspondencia) REFERENCES correspondencia (id_correspondencia),
    CONSTRAINT fk_archivo_expediente      FOREIGN KEY (id_expediente)      REFERENCES expediente (id_expediente)
);

-- Requisitos y documentación presentada por trámite (CU-10).
CREATE TABLE documento_tramite (
    id_documento INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_tramite   INTEGER NOT NULL,
    id_requisito INTEGER,                        -- NULL si es documento adicional
    id_archivo   INTEGER,                        -- NULL mientras no se adjunte
    es_requisito BOOLEAN NOT NULL DEFAULT TRUE,
    presentado   BOOLEAN NOT NULL DEFAULT FALSE,
    verificado   BOOLEAN NOT NULL DEFAULT FALSE,
    observacion  VARCHAR(300),
    CONSTRAINT pk_documento_tramite PRIMARY KEY (id_documento),
    CONSTRAINT fk_documento_tramite   FOREIGN KEY (id_tramite)   REFERENCES tramite (id_tramite),
    CONSTRAINT fk_documento_requisito FOREIGN KEY (id_requisito) REFERENCES requisito_tipo_tramite (id_requisito),
    CONSTRAINT fk_documento_archivo   FOREIGN KEY (id_archivo)   REFERENCES archivo_adjunto (id_archivo)
);

CREATE TABLE dictamen (
    id_dictamen INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_tramite  INTEGER     NOT NULL,
    fecha       DATE        NOT NULL,
    resultado   VARCHAR(20) NOT NULL,            -- FAVORABLE, DESFAVORABLE
    fundamento  TEXT        NOT NULL,
    CONSTRAINT pk_dictamen PRIMARY KEY (id_dictamen),
    CONSTRAINT uq_dictamen_tramite UNIQUE (id_tramite),
    CONSTRAINT fk_dictamen_tramite FOREIGN KEY (id_tramite) REFERENCES tramite (id_tramite)
);

-- =====================================================================
-- MÓDULO 4. GESTIÓN ACADÉMICA (6 tablas)
-- =====================================================================

CREATE TABLE periodo_academico (
    id_periodo               INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    gestion                  INTEGER     NOT NULL,
    semestre                 INTEGER     NOT NULL,
    fecha_inicio             DATE        NOT NULL,
    fecha_fin                DATE        NOT NULL,
    fecha_cierre_inscripcion DATE,
    estado                   VARCHAR(20) NOT NULL DEFAULT 'PLANIFICADO',  -- PLANIFICADO, ABIERTO, CERRADO
    CONSTRAINT pk_periodo_academico PRIMARY KEY (id_periodo),
    CONSTRAINT uq_periodo_gestion_semestre UNIQUE (gestion, semestre),
    CONSTRAINT ck_periodo_semestre CHECK (semestre IN (1, 2)),
    CONSTRAINT ck_periodo_fechas CHECK (fecha_fin > fecha_inicio)
);

CREATE TABLE materia (
    id_materia INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    sigla      VARCHAR(15)  NOT NULL,
    nombre     VARCHAR(150) NOT NULL,
    plan       VARCHAR(20)  NOT NULL,            -- 148-1, 148-2
    nivel      INTEGER      NOT NULL,
    horas      INTEGER      NOT NULL,
    CONSTRAINT pk_materia PRIMARY KEY (id_materia),
    CONSTRAINT uq_materia_sigla_plan UNIQUE (sigla, plan)
);

CREATE TABLE grupo (
    id_grupo   INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_materia INTEGER     NOT NULL,
    id_periodo INTEGER     NOT NULL,
    codigo     VARCHAR(10) NOT NULL,
    cupo       INTEGER     NOT NULL,
    inscritos  INTEGER     NOT NULL DEFAULT 0,
    turno      VARCHAR(10) NOT NULL,             -- MANANA, TARDE, NOCHE
    horario    VARCHAR(100),
    aula       VARCHAR(30),
    CONSTRAINT pk_grupo PRIMARY KEY (id_grupo),
    CONSTRAINT uq_grupo UNIQUE (id_materia, id_periodo, codigo),
    CONSTRAINT ck_grupo_cupo CHECK (cupo > 0 AND inscritos >= 0 AND inscritos <= cupo),
    CONSTRAINT fk_grupo_materia FOREIGN KEY (id_materia) REFERENCES materia (id_materia),
    CONSTRAINT fk_grupo_periodo FOREIGN KEY (id_periodo) REFERENCES periodo_academico (id_periodo)
);

CREATE TABLE asignacion_docente (
    id_asignacion   INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_docente      INTEGER     NOT NULL,
    id_grupo        INTEGER     NOT NULL,
    tipo            VARCHAR(20) NOT NULL,        -- TITULAR, INTERINO, COBERTURA
    horas_asignadas INTEGER     NOT NULL,
    fecha_inicio    DATE        NOT NULL,
    fecha_fin       DATE,
    observacion     VARCHAR(300),                -- antecedentes de cobertura
    CONSTRAINT pk_asignacion_docente PRIMARY KEY (id_asignacion),
    CONSTRAINT fk_asignacion_docente FOREIGN KEY (id_docente) REFERENCES docente (id_persona),
    CONSTRAINT fk_asignacion_grupo   FOREIGN KEY (id_grupo)   REFERENCES grupo (id_grupo)
);

CREATE TABLE inscripcion (
    id_inscripcion    INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_estudiante     INTEGER     NOT NULL,
    id_grupo          INTEGER     NOT NULL,
    fecha_inscripcion DATE        NOT NULL,
    estado            VARCHAR(20) NOT NULL DEFAULT 'INSCRITO',   -- INSCRITO, RETIRADO, APROBADO, REPROBADO
    es_caso_especial  BOOLEAN     NOT NULL DEFAULT FALSE,        -- adición fuera de fecha, cambio de grupo
    CONSTRAINT pk_inscripcion PRIMARY KEY (id_inscripcion),
    CONSTRAINT uq_inscripcion UNIQUE (id_estudiante, id_grupo),
    CONSTRAINT fk_inscripcion_estudiante FOREIGN KEY (id_estudiante) REFERENCES estudiante (id_persona),
    CONSTRAINT fk_inscripcion_grupo      FOREIGN KEY (id_grupo)      REFERENCES grupo (id_grupo)
);

-- id_trabajo se enlaza a trabajo_grado en el script de ajustes.
CREATE TABLE titulado (
    id_titulado   INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_estudiante INTEGER     NOT NULL,
    id_trabajo    INTEGER,
    gestion       INTEGER     NOT NULL,
    modalidad     VARCHAR(30) NOT NULL,          -- TESIS, PROYECTO_GRADO, EXCELENCIA, TRABAJO_DIRIGIDO
    fecha_defensa DATE,
    nro_diploma   VARCHAR(30),
    CONSTRAINT pk_titulado PRIMARY KEY (id_titulado),
    CONSTRAINT uq_titulado_estudiante UNIQUE (id_estudiante),
    CONSTRAINT fk_titulado_estudiante FOREIGN KEY (id_estudiante) REFERENCES estudiante (id_persona)
);

-- =====================================================================
-- MÓDULO 5. PLANIFICACIÓN POA (3 tablas)
-- =====================================================================

CREATE TABLE poa (
    id_poa   INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    gestion  INTEGER     NOT NULL,
    objetivo TEXT        NOT NULL,
    estado   VARCHAR(20) NOT NULL DEFAULT 'EN_EJECUCION',   -- FORMULADO, EN_EJECUCION, CERRADO
    CONSTRAINT pk_poa PRIMARY KEY (id_poa),
    CONSTRAINT uq_poa_gestion UNIQUE (gestion)
);

CREATE TABLE actividad_poa (
    id_actividad INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_poa       INTEGER      NOT NULL,
    descripcion  VARCHAR(300) NOT NULL,
    meta         VARCHAR(200) NOT NULL,
    responsable  VARCHAR(150),
    fecha_inicio DATE         NOT NULL,
    fecha_fin    DATE         NOT NULL,
    avance       NUMERIC(5,2) NOT NULL DEFAULT 0,
    estado       VARCHAR(20)  NOT NULL DEFAULT 'PENDIENTE',   -- PENDIENTE, EN_CURSO, CONCLUIDA, RETRASADA
    CONSTRAINT pk_actividad_poa PRIMARY KEY (id_actividad),
    CONSTRAINT ck_actividad_avance CHECK (avance BETWEEN 0 AND 100),
    CONSTRAINT fk_actividad_poa FOREIGN KEY (id_poa) REFERENCES poa (id_poa)
);

CREATE TABLE seguimiento_actividad (
    id_seguimiento INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_actividad   INTEGER      NOT NULL,
    fecha          DATE         NOT NULL,
    avance         NUMERIC(5,2) NOT NULL,
    observacion    TEXT,
    evidencia      VARCHAR(500),
    id_evento      INTEGER,                      -- FK a evento (script de ajustes)
    CONSTRAINT pk_seguimiento_actividad PRIMARY KEY (id_seguimiento),
    CONSTRAINT ck_seguimiento_avance CHECK (avance BETWEEN 0 AND 100),
    CONSTRAINT fk_seguimiento_actividad FOREIGN KEY (id_actividad) REFERENCES actividad_poa (id_actividad)
);

-- =====================================================================
-- MÓDULO 6. RPA E INFORMES (5 tablas)
-- =====================================================================

CREATE TABLE proceso_rpa (
    id_proceso            INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombre                VARCHAR(150) NOT NULL,
    descripcion           TEXT,
    version               VARCHAR(20)  NOT NULL,
    tipo_proceso          VARCHAR(50)  NOT NULL,             -- CONSOLIDACION_CORRESPONDENCIA
    estado                VARCHAR(20)  NOT NULL DEFAULT 'HABILITADO',  -- HABILITADO, DESHABILITADO
    tiempo_max_segundos   INTEGER      NOT NULL DEFAULT 300, -- 5 minutos (configurable)
    tiempo_manual_minutos INTEGER      NOT NULL DEFAULT 240, -- referencia para métricas
    CONSTRAINT pk_proceso_rpa PRIMARY KEY (id_proceso),
    CONSTRAINT uq_proceso_rpa_nombre UNIQUE (nombre)
);

-- id_ejecucion_origen: si es una reejecución, apunta a la ejecución anterior.
CREATE TABLE ejecucion_rpa (
    id_ejecucion          INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_proceso            INTEGER     NOT NULL,
    id_usuario            INTEGER     NOT NULL,              -- quien inicia (Apoyo Profesional)
    id_usuario_revisor    INTEGER     NOT NULL,              -- revisor elegido (Director/Coordinador)
    id_ejecucion_origen   INTEGER,
    periodo_desde         DATE        NOT NULL,
    periodo_hasta         DATE        NOT NULL,
    tipo_correspondencia  VARCHAR(20) NOT NULL DEFAULT 'TODAS',  -- RECIBIDA, EMITIDA, TODAS
    estado                VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE', -- PENDIENTE, EN_PROCESO, COMPLETADA, FALLIDA
    fecha_inicio          TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_fin             TIMESTAMP,
    duracion_ms           BIGINT,
    registros_procesados  INTEGER     NOT NULL DEFAULT 0,
    registros_validos     INTEGER     NOT NULL DEFAULT 0,
    errores_detectados    INTEGER     NOT NULL DEFAULT 0,
    log_pasos             JSONB,                             -- evidencias: registro de pasos
    mensaje_error         TEXT,
    CONSTRAINT pk_ejecucion_rpa PRIMARY KEY (id_ejecucion),
    CONSTRAINT ck_ejecucion_estado CHECK (estado IN ('PENDIENTE', 'EN_PROCESO', 'COMPLETADA', 'FALLIDA')),
    CONSTRAINT ck_ejecucion_periodo CHECK (periodo_hasta >= periodo_desde),
    CONSTRAINT fk_ejecucion_proceso FOREIGN KEY (id_proceso)          REFERENCES proceso_rpa (id_proceso),
    CONSTRAINT fk_ejecucion_usuario FOREIGN KEY (id_usuario)          REFERENCES usuario (id_usuario),
    CONSTRAINT fk_ejecucion_revisor FOREIGN KEY (id_usuario_revisor)  REFERENCES usuario (id_usuario),
    CONSTRAINT fk_ejecucion_origen  FOREIGN KEY (id_ejecucion_origen) REFERENCES ejecucion_rpa (id_ejecucion)
);
-- Una ejecución solo puede reejecutarse una vez (evita ramas y duplicados).
CREATE UNIQUE INDEX uq_ejecucion_origen ON ejecucion_rpa (id_ejecucion_origen) WHERE id_ejecucion_origen IS NOT NULL;

-- Un informe por ejecución (uq_informe_ejecucion): una reejecución crea su propio informe
-- y el anterior queda DEVUELTO o ANULADO, nunca dos informes vigentes del mismo periodo.
CREATE TABLE informe_mensual (
    id_informe             INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_ejecucion           INTEGER      NOT NULL,
    id_plantilla           INTEGER      NOT NULL,
    periodo_desde          DATE         NOT NULL,
    periodo_hasta          DATE         NOT NULL,
    total_recibidos        INTEGER      NOT NULL DEFAULT 0,
    total_emitidos         INTEGER      NOT NULL DEFAULT 0,
    ruta_pdf               VARCHAR(500) NOT NULL,
    hash_sha256            CHAR(64),
    fecha_generacion       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    estado_revision        VARCHAR(30)  NOT NULL DEFAULT 'PENDIENTE_REVISION', -- PENDIENTE_REVISION, APROBADO, DEVUELTO, ANULADO
    observaciones_revision TEXT,
    fecha_revision         TIMESTAMP,
    CONSTRAINT pk_informe_mensual PRIMARY KEY (id_informe),
    CONSTRAINT uq_informe_ejecucion UNIQUE (id_ejecucion),
    CONSTRAINT ck_informe_estado CHECK (estado_revision IN ('PENDIENTE_REVISION', 'APROBADO', 'DEVUELTO', 'ANULADO')),
    CONSTRAINT fk_informe_ejecucion FOREIGN KEY (id_ejecucion) REFERENCES ejecucion_rpa (id_ejecucion),
    CONSTRAINT fk_informe_plantilla FOREIGN KEY (id_plantilla) REFERENCES plantilla_documento (id_plantilla)
);

CREATE TABLE detalle_informe (
    id_detalle INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_informe INTEGER      NOT NULL,
    categoria  VARCHAR(20)  NOT NULL,            -- FECHA, TIPO, ESTADO, DEPENDENCIA
    clave      VARCHAR(150) NOT NULL,
    cantidad   INTEGER      NOT NULL,
    CONSTRAINT pk_detalle_informe PRIMARY KEY (id_detalle),
    CONSTRAINT uq_detalle_informe UNIQUE (id_informe, categoria, clave),
    CONSTRAINT fk_detalle_informe FOREIGN KEY (id_informe) REFERENCES informe_mensual (id_informe)
);

-- Un único correo por informe (uq_notificacion_informe): impide envíos duplicados.
CREATE TABLE notificacion_correo (
    id_notificacion     INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_informe          INTEGER      NOT NULL,
    destinatarios       VARCHAR(1000) NOT NULL,  -- correos separados por coma
    asunto              VARCHAR(300) NOT NULL,
    cuerpo              TEXT         NOT NULL,
    estado              VARCHAR(20)  NOT NULL DEFAULT 'BORRADOR', -- BORRADOR, AUTORIZADO, ENVIADO, ERROR, ANULADO
    id_usuario_autoriza INTEGER,
    fecha_autorizacion  TIMESTAMP,
    fecha_envio         TIMESTAMP,
    mensaje_error       TEXT,
    CONSTRAINT pk_notificacion_correo PRIMARY KEY (id_notificacion),
    CONSTRAINT uq_notificacion_informe UNIQUE (id_informe),
    CONSTRAINT ck_notificacion_estado CHECK (estado IN ('BORRADOR', 'AUTORIZADO', 'ENVIADO', 'ERROR', 'ANULADO')),
    -- Regla de negocio: no hay envío sin autorización humana.
    CONSTRAINT ck_notificacion_autorizada CHECK (
        estado NOT IN ('AUTORIZADO', 'ENVIADO') OR (id_usuario_autoriza IS NOT NULL AND fecha_autorizacion IS NOT NULL)
    ),
    CONSTRAINT fk_notificacion_informe FOREIGN KEY (id_informe)          REFERENCES informe_mensual (id_informe),
    CONSTRAINT fk_notificacion_usuario FOREIGN KEY (id_usuario_autoriza) REFERENCES usuario (id_usuario)
);

