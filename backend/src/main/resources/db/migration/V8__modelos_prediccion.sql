-- =====================================================================
-- V8: historial de versiones del modelo predictivo (CU-29).
-- servicios-ia guarda cada modelo entrenado (demora-v<versión>.joblib) en el
-- volumen "modelos-ia"; aquí se registra quién lo entrenó, cuándo, con cuántos
-- ejemplos, su exactitud y su SHA-256, y cuál es la versión vigente.
-- Agrega 1 tabla (el modelo pasa de 44 a 45 tablas). No modifica las existentes.
-- =====================================================================
CREATE TABLE modelo_prediccion (
    id_modelo           INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    version             INTEGER      NOT NULL,
    algoritmo           VARCHAR(50)  NOT NULL,
    fecha_entrenamiento TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ejemplos            INTEGER      NOT NULL,
    demorados           INTEGER      NOT NULL,
    exactitud           NUMERIC(4,3),                     -- validación cruzada (0 a 1); NULL si no hubo pliegues
    hash_sha256         VARCHAR(64),                      -- SHA-256 del archivo .joblib (NULL si no se guardó)
    id_usuario          INTEGER,                          -- quién lo entrenó (NULL si fue automático)
    vigente             BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT pk_modelo_prediccion PRIMARY KEY (id_modelo),
    CONSTRAINT uq_modelo_prediccion_version UNIQUE (version),
    CONSTRAINT fk_modelo_prediccion_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario),
    CONSTRAINT ck_modelo_prediccion_conteos CHECK (ejemplos > 0 AND demorados >= 0 AND demorados <= ejemplos)
);

-- Una sola versión vigente
CREATE UNIQUE INDEX uq_modelo_prediccion_vigente ON modelo_prediccion (vigente) WHERE vigente;
