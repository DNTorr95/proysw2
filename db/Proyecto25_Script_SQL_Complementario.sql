-- ---------------- Seguridad: permisos por rol ----------------
CREATE TABLE permiso (
    id_permiso INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    codigo     VARCHAR(80)  NOT NULL,
    modulo     VARCHAR(80)  NOT NULL,
    descripcion VARCHAR(200),
    CONSTRAINT pk_permiso PRIMARY KEY (id_permiso),
    CONSTRAINT uq_permiso_codigo UNIQUE (codigo)
);

CREATE TABLE rol_permiso (
    id_rol     INTEGER NOT NULL,
    id_permiso INTEGER NOT NULL,
    CONSTRAINT pk_rol_permiso PRIMARY KEY (id_rol, id_permiso),
    CONSTRAINT fk_rol_permiso_rol     FOREIGN KEY (id_rol)     REFERENCES rol (id_rol),
    CONSTRAINT fk_rol_permiso_permiso FOREIGN KEY (id_permiso) REFERENCES permiso (id_permiso)
);

-- ---------------- Control de estados (Spring State Machine) ----------------
CREATE TABLE estado_tramite (
    id_estado INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombre    VARCHAR(30) NOT NULL,
    es_final  BOOLEAN     NOT NULL DEFAULT FALSE,
    CONSTRAINT pk_estado_tramite PRIMARY KEY (id_estado),
    CONSTRAINT uq_estado_tramite_nombre UNIQUE (nombre)
);

CREATE TABLE transicion_estado (
    id_transicion     INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_estado_origen  INTEGER     NOT NULL,
    id_estado_destino INTEGER     NOT NULL,
    evento            VARCHAR(50) NOT NULL,
    guarda            VARCHAR(200),
    CONSTRAINT pk_transicion_estado PRIMARY KEY (id_transicion),
    CONSTRAINT fk_transicion_origen  FOREIGN KEY (id_estado_origen)  REFERENCES estado_tramite (id_estado),
    CONSTRAINT fk_transicion_destino FOREIGN KEY (id_estado_destino) REFERENCES estado_tramite (id_estado)
);

-- ---------------- Automatización RPA: incidencias ----------------
CREATE TABLE incidencia_rpa (
    id_incidencia     INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_ejecucion      INTEGER     NOT NULL,
    tipo              VARCHAR(50) NOT NULL,
    descripcion       TEXT,
    estado            VARCHAR(30) NOT NULL,
    id_reejecucion    INTEGER,
    fecha_registro    TIMESTAMP   NOT NULL,
    CONSTRAINT pk_incidencia_rpa PRIMARY KEY (id_incidencia),
    CONSTRAINT fk_incidencia_ejecucion   FOREIGN KEY (id_ejecucion)   REFERENCES ejecucion_rpa (id_ejecucion),
    CONSTRAINT fk_incidencia_reejecucion FOREIGN KEY (id_reejecucion) REFERENCES ejecucion_rpa (id_ejecucion)
);

-- ---------------- Componentes de los otros grupos ----------------
CREATE TABLE alerta (
    id_alerta        INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_tramite       INTEGER      NOT NULL,
    origen           VARCHAR(20)  NOT NULL,   -- PLAZO o PREDICCION
    nivel            VARCHAR(20)  NOT NULL,   -- ALTA, MEDIA, BAJA
    probabilidad     NUMERIC(5,2),
    motivo           VARCHAR(200) NOT NULL,
    estado           VARCHAR(20)  NOT NULL,   -- ABIERTA, EN_ATENCION, ATENDIDA
    fecha_generacion TIMESTAMP    NOT NULL,
    id_usuario_atencion INTEGER,
    fecha_atencion   TIMESTAMP,
    CONSTRAINT pk_alerta PRIMARY KEY (id_alerta),
    CONSTRAINT fk_alerta_tramite FOREIGN KEY (id_tramite) REFERENCES tramite (id_tramite),
    CONSTRAINT fk_alerta_usuario FOREIGN KEY (id_usuario_atencion) REFERENCES usuario (id_usuario)
);

CREATE TABLE extraccion_ocr (
    id_extraccion  INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_archivo     INTEGER      NOT NULL,
    texto_extraido TEXT         NOT NULL,
    confianza      NUMERIC(5,2) NOT NULL,
    validado       BOOLEAN      NOT NULL DEFAULT FALSE,
    id_usuario_validacion INTEGER,
    fecha_validacion TIMESTAMP,
    CONSTRAINT pk_extraccion_ocr PRIMARY KEY (id_extraccion),
    CONSTRAINT uq_extraccion_archivo UNIQUE (id_archivo),
    CONSTRAINT fk_extraccion_archivo FOREIGN KEY (id_archivo) REFERENCES archivo_adjunto (id_archivo),
    CONSTRAINT fk_extraccion_usuario FOREIGN KEY (id_usuario_validacion) REFERENCES usuario (id_usuario)
);

-- ---------------- Gestión académica e institucional ----------------
CREATE TABLE trabajo_grado (
    id_trabajo     INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_estudiante  INTEGER      NOT NULL,
    titulo         VARCHAR(300) NOT NULL,
    tutor          VARCHAR(150),
    gestion        INTEGER      NOT NULL,
    palabras_clave VARCHAR(300),
    id_archivo     INTEGER,
    CONSTRAINT pk_trabajo_grado PRIMARY KEY (id_trabajo),
    CONSTRAINT fk_trabajo_estudiante FOREIGN KEY (id_estudiante) REFERENCES estudiante (id_persona),
    CONSTRAINT fk_trabajo_archivo    FOREIGN KEY (id_archivo)    REFERENCES archivo_adjunto (id_archivo)
);

CREATE TABLE registro_migracion (
    id_migracion  INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_estudiante INTEGER     NOT NULL,
    plan_origen   VARCHAR(20) NOT NULL,
    plan_destino  VARCHAR(20) NOT NULL,
    fecha         DATE        NOT NULL,
    observacion   TEXT,
    CONSTRAINT pk_registro_migracion PRIMARY KEY (id_migracion),
    CONSTRAINT fk_migracion_estudiante FOREIGN KEY (id_estudiante) REFERENCES estudiante (id_persona)
);

CREATE TABLE evento (
    id_evento     INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombre        VARCHAR(150) NOT NULL,
    tipo          VARCHAR(50)  NOT NULL,   -- TALLER, SEMINARIO, EVENTO
    fecha         DATE         NOT NULL,
    responsable   VARCHAR(150),
    id_actividad  INTEGER,
    CONSTRAINT pk_evento PRIMARY KEY (id_evento),
    CONSTRAINT fk_evento_actividad FOREIGN KEY (id_actividad) REFERENCES actividad_poa (id_actividad)
);

